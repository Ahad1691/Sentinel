"use client";

import { FormEvent, useEffect, useState } from "react";

type Severity = "Critical" | "High" | "Medium" | "Low" | "Info";

type Issue = {
  title: string;
  severity: Severity | string;
  plainEnglishExplanation: string;
  technicalDetail: string;
  historicalMatch: string | null;
  historicalMatchSummary: string | null;
};

type Report = {
  overallRiskScore: number;
  summary: string;
  issues: Issue[];
};

type ScanSuccess = {
  address: string;
  contractName: string | null;
  truncated: boolean;
  report: Report;
};

const EXAMPLE_CONTRACTS = [
  {
    label: "Try USDC",
    address: "0xA0b86991c6218b36c1d19D4a2e9Eb0cE3606eB48",
  },
  {
    label: "Try Uniswap Router",
    address: "0x7a250d5630B4cF539739dF2C5dAcb4c659F2488D",
  },
  {
    label: "Try WETH",
    address: "0xC02aaA39b223FE8D0A0e5C4F27eAD9083C756Cc2",
  },
] as const;

const LOADING_MESSAGES = [
  "Fetching contract source...",
  "Analyzing with AI...",
] as const;

function riskTone(score: number): { bg: string; text: string; label: string } {
  if (score <= 3) {
    return { bg: "bg-[var(--success-soft)]", text: "text-[var(--success)]", label: "Low risk" };
  }
  if (score <= 6) {
    return { bg: "bg-[var(--warn-soft)]", text: "text-[var(--warn)]", label: "Moderate risk" };
  }
  return { bg: "bg-[var(--danger-soft)]", text: "text-[var(--danger)]", label: "High risk" };
}

function severityTone(severity: string): string {
  switch (severity) {
    case "Critical":
      return "bg-red-500/20 text-red-300 border-red-500/30";
    case "High":
      return "bg-orange-500/20 text-orange-300 border-orange-500/30";
    case "Medium":
      return "bg-yellow-500/20 text-yellow-200 border-yellow-500/30";
    case "Low":
      return "bg-sky-500/20 text-sky-300 border-sky-500/30";
    default:
      return "bg-slate-500/20 text-slate-300 border-slate-500/30";
  }
}

function formatReportAsText(data: ScanSuccess): string {
  const { report, address, contractName } = data;
  const lines = [
    "Sentinel Security Report",
    "========================",
    `Address: ${address}`,
    contractName ? `Contract: ${contractName}` : null,
    `Overall Risk Score: ${report.overallRiskScore}/10`,
    `Summary: ${report.summary}`,
    "",
    report.issues.length === 0
      ? "No issues found."
      : `Issues (${report.issues.length}):`,
  ].filter((line): line is string => line !== null);

  report.issues.forEach((issue, index) => {
    lines.push("");
    lines.push(`${index + 1}. [${issue.severity}] ${issue.title}`);
    lines.push(`   ${issue.plainEnglishExplanation}`);
    lines.push(`   Technical: ${issue.technicalDetail}`);
    if (issue.historicalMatch) {
      lines.push(
        `   Resembles: ${issue.historicalMatch} — ${issue.historicalMatchSummary ?? ""}`
      );
    }
  });

  lines.push("");
  lines.push("Generated by Sentinel · AI analysis is not a substitute for a professional audit.");
  return lines.join("\n");
}

export default function Home() {
  const [address, setAddress] = useState("");
  const [loading, setLoading] = useState(false);
  const [cooldown, setCooldown] = useState(false);
  const [loadingMsgIndex, setLoadingMsgIndex] = useState(0);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<ScanSuccess | null>(null);
  const [expanded, setExpanded] = useState<Record<number, boolean>>({});
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    if (!loading) {
      setLoadingMsgIndex(0);
      return;
    }
    const id = window.setInterval(() => {
      setLoadingMsgIndex((prev) => (prev + 1) % LOADING_MESSAGES.length);
    }, 2000);
    return () => window.clearInterval(id);
  }, [loading]);

  async function runScan(targetAddress: string) {
    const trimmed = targetAddress.trim();
    if (!trimmed || loading || cooldown) return;

    setLoading(true);
    setCooldown(true);
    setError(null);
    setResult(null);
    setExpanded({});
    setCopied(false);

    window.setTimeout(() => setCooldown(false), 3000);

    try {
      const res = await fetch("/api/scan", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ address: trimmed }),
      });

      const data = (await res.json()) as ScanSuccess & { error?: string };

      if (!res.ok || data.error) {
        setError(data.error || "Scan failed. Please try again.");
        return;
      }

      setResult(data);
    } catch {
      setError("Network error. Check your connection and try again.");
    } finally {
      setLoading(false);
    }
  }

  function handleSubmit(event: FormEvent) {
    event.preventDefault();
    void runScan(address);
  }

  async function handleCopy() {
    if (!result) return;
    try {
      await navigator.clipboard.writeText(formatReportAsText(result));
      setCopied(true);
      window.setTimeout(() => setCopied(false), 2000);
    } catch {
      setError("Could not copy to clipboard.");
    }
  }

  const scanDisabled = loading || cooldown || !address.trim();
  const scoreTone = result ? riskTone(result.report.overallRiskScore) : null;

  return (
    <main className="min-h-screen px-4 py-10 sm:px-6 sm:py-14">
      <div className="mx-auto flex w-full max-w-[800px] flex-col gap-8">
        <header className="text-center space-y-3">
          <h1 className="text-4xl sm:text-5xl font-bold tracking-tight">
            🛡️ Sentinel
          </h1>
          <p className="text-[var(--muted)] text-base sm:text-lg">
            AI-Powered Smart Contract Security Scanner
          </p>
          <p className="text-xs sm:text-sm text-slate-500">
            Scans are not stored — your data stays private
          </p>
        </header>

        <section className="rounded-2xl border border-[var(--border)] bg-[var(--bg-elevated)]/80 p-5 sm:p-6 shadow-[0_0_0_1px_rgba(59,130,246,0.04)] backdrop-blur">
          <form onSubmit={handleSubmit} className="space-y-4">
            <label htmlFor="address" className="sr-only">
              Ethereum contract address
            </label>
            <input
              id="address"
              type="text"
              value={address}
              onChange={(e) => setAddress(e.target.value)}
              placeholder="Paste an Ethereum contract address (0x...)"
              spellCheck={false}
              className="w-full rounded-xl border border-[var(--border)] bg-[var(--bg-panel)] px-4 py-3.5 text-sm sm:text-base text-white placeholder:text-slate-500 outline-none transition focus:border-[var(--accent)] focus:ring-2 focus:ring-[var(--accent-soft)]"
            />

            <button
              type="submit"
              disabled={scanDisabled}
              className="w-full rounded-xl bg-[var(--accent)] px-4 py-3.5 text-sm sm:text-base font-semibold text-white transition hover:bg-blue-500 disabled:cursor-not-allowed disabled:opacity-50"
            >
              {loading ? "Scanning..." : cooldown ? "Please wait..." : "Scan Contract"}
            </button>
          </form>

          <div className="mt-4 flex flex-wrap gap-2">
            {EXAMPLE_CONTRACTS.map((example) => (
              <button
                key={example.address}
                type="button"
                onClick={() => setAddress(example.address)}
                className="rounded-lg border border-[var(--border)] bg-[var(--bg-panel)] px-3 py-1.5 text-xs sm:text-sm text-slate-300 transition hover:border-[var(--accent)] hover:text-white"
              >
                {example.label}
              </button>
            ))}
          </div>
        </section>

        {loading && (
          <div className="animate-fade-in flex items-center justify-center gap-3 rounded-xl border border-[var(--border)] bg-[var(--bg-elevated)]/70 px-4 py-6 text-[var(--muted)]">
            <div className="spinner" aria-hidden />
            <p className="text-sm sm:text-base">{LOADING_MESSAGES[loadingMsgIndex]}</p>
          </div>
        )}

        {error && !loading && (
          <div className="animate-fade-in rounded-xl border border-red-500/30 bg-[var(--danger-soft)] px-4 py-4 sm:px-5">
            <p className="text-red-200 text-sm sm:text-base">{error}</p>
            <button
              type="button"
              onClick={() => void runScan(address)}
              disabled={!address.trim() || cooldown}
              className="mt-3 text-sm font-medium text-red-100 underline underline-offset-2 hover:text-white disabled:opacity-50"
            >
              Retry scan
            </button>
          </div>
        )}

        {result && !loading && scoreTone && (
          <section className="animate-fade-in space-y-5">
            <div className="rounded-2xl border border-[var(--border)] bg-[var(--bg-elevated)]/80 p-5 sm:p-6 space-y-5">
              <div className="flex flex-col sm:flex-row sm:items-center gap-4 justify-between">
                <div
                  className={`inline-flex items-center gap-3 rounded-2xl px-4 py-3 ${scoreTone.bg}`}
                >
                  <span className={`text-4xl sm:text-5xl font-bold tabular-nums ${scoreTone.text}`}>
                    {result.report.overallRiskScore}
                  </span>
                  <div className="text-left">
                    <p className={`text-sm font-semibold ${scoreTone.text}`}>/ 10</p>
                    <p className="text-xs text-slate-400">{scoreTone.label}</p>
                  </div>
                </div>

                <button
                  type="button"
                  onClick={() => void handleCopy()}
                  className="rounded-xl border border-[var(--border)] bg-[var(--bg-panel)] px-4 py-2.5 text-sm text-slate-200 transition hover:border-[var(--accent)] hover:text-white"
                >
                  {copied ? "Copied!" : "Copy Report"}
                </button>
              </div>

              <p className="text-lg sm:text-xl leading-relaxed text-slate-100">
                {result.report.summary}
              </p>

              {result.contractName && (
                <p className="text-xs text-slate-500">
                  Contract: {result.contractName}
                  {result.truncated ? " · Source truncated for analysis" : ""}
                </p>
              )}
            </div>

            {result.report.issues.length === 0 ? (
              <div className="rounded-2xl border border-green-500/25 bg-[var(--success-soft)] px-5 py-6 space-y-2">
                <p className="text-lg font-semibold text-green-300">
                  No issues found in this scan
                </p>
                <p className="text-sm text-green-100/80 leading-relaxed">
                  Looking good from an automated pass — but AI analysis isn&apos;t a
                  substitute for a professional security audit before you put real
                  funds at risk.
                </p>
              </div>
            ) : (
              <ul className="space-y-3">
                {result.report.issues.map((issue, index) => {
                  const open = !!expanded[index];
                  return (
                    <li
                      key={`${issue.title}-${index}`}
                      className="rounded-2xl border border-[var(--border)] bg-[var(--bg-elevated)]/80 p-4 sm:p-5 space-y-3"
                    >
                      <div className="flex flex-wrap items-center gap-2">
                        <span
                          className={`rounded-md border px-2 py-0.5 text-xs font-semibold ${severityTone(issue.severity)}`}
                        >
                          {issue.severity}
                        </span>
                        <h3 className="text-base sm:text-lg font-semibold text-white">
                          {issue.title}
                        </h3>
                      </div>

                      <p className="text-sm sm:text-base text-slate-300 leading-relaxed">
                        {issue.plainEnglishExplanation}
                      </p>

                      <button
                        type="button"
                        onClick={() =>
                          setExpanded((prev) => ({ ...prev, [index]: !prev[index] }))
                        }
                        className="text-sm text-[var(--accent)] hover:underline underline-offset-2"
                      >
                        {open ? "Hide Technical Details" : "Technical Details"}
                      </button>

                      {open && (
                        <p className="animate-fade-in rounded-xl bg-[var(--bg-panel)] border border-[var(--border)] px-3 py-3 text-sm text-slate-400 font-[family-name:var(--font-geist-mono)] leading-relaxed">
                          {issue.technicalDetail}
                        </p>
                      )}

                      {issue.historicalMatch && (
                        <div className="rounded-xl border border-amber-500/30 bg-amber-500/10 px-3 py-3 text-sm text-amber-100">
                          ⚠️ Resembles: {issue.historicalMatch}
                          {issue.historicalMatchSummary
                            ? ` — ${issue.historicalMatchSummary}`
                            : ""}
                        </div>
                      )}
                    </li>
                  );
                })}
              </ul>
            )}
          </section>
        )}

        <footer className="pt-4 pb-2 text-center text-xs sm:text-sm text-slate-500">
          Powered by Google Gemini · Built for ETHGlobal
        </footer>
      </div>
    </main>
  );
}
